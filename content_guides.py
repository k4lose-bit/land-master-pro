def guides_check():
    """가이드 정의가 실제 용어 데이터와 맞는지 빌드 시점에 검증한다."""
    from content_terms import TERMS as T1
    from content_terms2 import TERMS2 as T2
    terms = {t["slug"]: t for t in (T1 + T2)}
    seen = set()
    slugs = set()
    for g in GUIDES:
        if g["slug"] in slugs:
            raise SystemExit("content_guides: 가이드 slug 중복 → %s" % g["slug"])
        slugs.add(g["slug"])
        for s in g["order"]:
            if s not in terms:
                raise SystemExit("content_guides: 없는 용어 slug → %s" % s)
            if s in seen:
                raise SystemExit("content_guides: 용어가 두 가이드에 중복 → %s" % s)
            if terms[s]["group"] != g["group"]:
                raise SystemExit(
                    "content_guides: 그룹 불일치 → %s (용어 %s / 가이드 %s)"
                    % (s, terms[s]["group"], g["group"]))
            seen.add(s)
    missing = set(terms) - seen
    if missing:
        raise SystemExit("content_guides: 가이드에 담기지 않은 용어 → %s" % sorted(missing))


# 용어 slug → 그 용어가 들어간 가이드 페이지의 앵커 링크
def term_href_map():
    out = {}
    for g in GUIDES:
        for s in g["order"]:
            out[s] = "guide-%s.html#term-%s" % (g["slug"], s)
    return out
